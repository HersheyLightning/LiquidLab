package com.hersh.liquid_lab.util;

public class FogProperties {
    public final float fogStart;
    public final float fogEnd;
    public final float red;
    public final float green;
    public final float blue;

    public FogProperties(float fogStart, float fogEnd, float red, float green, float blue) {
        this.fogStart = fogStart;
        this.fogEnd = fogEnd;
        this.red = red;
        this.green = green;
        this.blue = blue;
    }
}
